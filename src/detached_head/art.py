def make_minimap_banner(lvl, w: int = 960, h: int = 600) -> Image.Image:
    """Standalone map overview for the README."""
    img = _img(w, h, BG + (255,))
    d = ImageDraw.Draw(img)
    cell = 20
    ox = (w - lvl.width * cell) // 2
    oy = (h - lvl.height * cell) // 2
    palette = {"arena": (70, 20, 20), "keyroom": (60, 50, 12), "gate": (70, 60, 20)}
    for y in range(lvl.height):
        for x in range(lvl.width):
            c = lvl.char(x, y)
            if lvl.is_floor(x, y):
                z = lvl.zone(x, y)
                color = palette.get(z, (27, 33, 41))
                if c == "G":
                    color = AMBER
                d.rectangle([ox + x * cell, oy + y * cell, ox + x * cell + cell - 2, oy + y * cell + cell - 2], fill=color)
            else:
                d.rectangle([ox + x * cell, oy + y * cell, ox + x * cell + cell - 2, oy + y * cell + cell - 2], fill=(13, 17, 23), outline=(48, 54, 61))
    d.ellipse([ox + lvl.spawn[0] * cell + 4, oy + lvl.spawn[1] * cell + 4, ox + lvl.spawn[0] * cell + cell - 6, oy + lvl.spawn[1] * cell + cell - 6], fill=GREEN)
    d.text((w // 2, oy - 40), "repo-01 \u00b7 the repository", font=_font(30, bold=True), fill=GREEN, anchor="mm")
    d.text((w // 2, h - 40), "find the key \u00b7 open the gate \u00b7 slay THE DEBT", font=_font(20), fill=GRAY, anchor="mm")
    return _scanlines(img)
