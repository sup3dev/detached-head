def _scanlines(img: Image.Image) -> Image.Image:
    px = img.load()
    for y in range(3, img.height, 3):
        for x in range(img.width):
            r, g, b, a = px[x, y]
            px[x, y] = (int(r * 0.72), int(g * 0.72), int(b * 0.72), a)
    return img


